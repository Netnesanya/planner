import { readdir, readFile, writeFile } from "node:fs/promises";

const directory = new URL("../supabase/migrations/", import.meta.url);
const files = (await readdir(directory))
  .filter((file) => file.endsWith(".sql"))
  .sort();
const migrations = await Promise.all(
  files.map(async (file) => {
    const sql = await readFile(new URL(file, directory), "utf8");
    return `-- ${file}\n${sql
      .replace(/^begin;\s*$/gim, "")
      .replace(/^commit;\s*$/gim, "")
      .trim()}`;
  }),
);
const header = `-- Flow Planner: initial installation into an empty Supabase project.\n-- Generated by npm run db:bundle. Run this file once in SQL Editor.\n-- Existing installations must apply individual new migrations instead.\n-- A single transaction prevents a partially installed schema.\n`;
await writeFile(
  new URL("../supabase/setup.sql", import.meta.url),
  `${header}begin;\n\n${migrations.join("\n\n")}\n\ncommit;\n`,
);
console.log(`Bundled ${files.length} migrations into supabase/setup.sql`);
